export function translate(key, locale, options = {}) {
  const resourceValue = readResource(key, locale);
  const value = resourceValue ?? UI_STRINGS[key];
  if (value === undefined) return key;
  const text = typeof value === "object" ? (normalizeLocale(locale) === LOCALES.OR ? value.or : value.en) : value;
  return String(text ?? key).replace(/{{\s*(\w+)\s*}}/g, (_, name) => String(options[name] ?? ""));
}

export function useLocaleText(locale) {
  return (key) => translate(key, locale);
}
