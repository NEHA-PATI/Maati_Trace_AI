export function translateLiteral(value, locale) {
  if (locale !== "or" || typeof value !== "string") return value;
  if (LITERAL_TRANSLATIONS[value]) return LITERAL_TRANSLATIONS[value];

  // Reuse the established catalogue for literals that were already registered
  // there but were not yet converted from JSX to t(...).
  const stack = Object.values(UI_STRINGS);
  while (stack.length) {
    const item = stack.pop();
    if (!item || typeof item !== "object") continue;
    if (item.en === value && item.or) return item.or;
    for (const child of Object.values(item)) {
      if (child && typeof child === "object") stack.push(child);
    }
  }
  return value;
}
